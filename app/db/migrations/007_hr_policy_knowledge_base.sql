
-- ============================================================
-- Migration 007: HR Policy Knowledge Base
-- Project: AI-Powered HRMS
-- Database: hrms_db
-- PostgreSQL: 17.5
-- pgvector: 0.8.7
-- Embedding model: gemini-embedding-001
-- Embedding dimensions: 3072
-- Vector storage: halfvec(3072)
-- ============================================================

BEGIN;

-- ------------------------------------------------------------
-- 1. HR POLICIES
-- Stores the identity and lifecycle of each policy.
-- ------------------------------------------------------------

CREATE TABLE hr_policies (
    policy_id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,

    policy_code VARCHAR(50) NOT NULL UNIQUE,
    policy_title VARCHAR(250) NOT NULL,
    policy_category VARCHAR(100) NOT NULL,
    description TEXT,

    department_id BIGINT
        REFERENCES departments(department_id)
        ON DELETE SET NULL,

    owner_user_id BIGINT
        REFERENCES users(user_id)
        ON DELETE SET NULL,

    status VARCHAR(20) NOT NULL DEFAULT 'draft',

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_hr_policies_status
        CHECK (
            status IN (
                'draft',
                'pending_review',
                'approved',
                'published',
                'archived',
                'rejected'
            )
        ),

    CONSTRAINT chk_hr_policies_code_not_blank
        CHECK (BTRIM(policy_code) <> ''),

    CONSTRAINT chk_hr_policies_title_not_blank
        CHECK (BTRIM(policy_title) <> ''),

    CONSTRAINT chk_hr_policies_category_not_blank
        CHECK (BTRIM(policy_category) <> '')
);

-- ------------------------------------------------------------
-- 2. HR POLICY VERSIONS
-- Each revision is retained as a separate record.
-- ------------------------------------------------------------

CREATE TABLE hr_policy_versions (
    policy_version_id BIGINT
        GENERATED ALWAYS AS IDENTITY PRIMARY KEY,

    policy_id BIGINT NOT NULL
        REFERENCES hr_policies(policy_id)
        ON DELETE RESTRICT,

    version_number INTEGER NOT NULL,

    version_label VARCHAR(50),

    status VARCHAR(20) NOT NULL DEFAULT 'draft',

    effective_from DATE,
    effective_to DATE,

    submitted_at TIMESTAMPTZ,

    approved_by_user_id BIGINT
        REFERENCES users(user_id)
        ON DELETE SET NULL,

    approved_at TIMESTAMPTZ,

    published_at TIMESTAMPTZ,

    source_file_name VARCHAR(500),
    source_reference TEXT,

    change_summary TEXT,

    created_by_user_id BIGINT
        REFERENCES users(user_id)
        ON DELETE SET NULL,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_hr_policy_version_number
        UNIQUE (policy_id, version_number),

    CONSTRAINT chk_hr_policy_version_positive
        CHECK (version_number > 0),

    CONSTRAINT chk_hr_policy_version_status
        CHECK (
            status IN (
                'draft',
                'pending_review',
                'approved',
                'published',
                'archived',
                'rejected'
            )
        ),

    CONSTRAINT chk_hr_policy_effective_dates
        CHECK (
            effective_to IS NULL
            OR effective_from IS NULL
            OR effective_to >= effective_from
        ),

    CONSTRAINT chk_hr_policy_approval_metadata
        CHECK (
            (approved_at IS NULL AND approved_by_user_id IS NULL)
            OR
            (approved_at IS NOT NULL AND approved_by_user_id IS NOT NULL)
        ),

    CONSTRAINT chk_hr_policy_published_metadata
        CHECK (
            status <> 'published'
            OR published_at IS NOT NULL
        )
);

-- ------------------------------------------------------------
-- 3. HR POLICY CHUNKS
-- Stores the text sections used for RAG retrieval.
-- Embeddings remain NULL until generated by the AI backend.
-- ------------------------------------------------------------

CREATE TABLE hr_policy_chunks (
    policy_chunk_id BIGINT
        GENERATED ALWAYS AS IDENTITY PRIMARY KEY,

    policy_version_id BIGINT NOT NULL
        REFERENCES hr_policy_versions(policy_version_id)
        ON DELETE RESTRICT,

    chunk_number INTEGER NOT NULL,

    section_heading VARCHAR(500),

    chunk_text TEXT NOT NULL,

    page_number INTEGER,

    source_reference TEXT,

    -- Gemini embedding model configuration
    embedding_model VARCHAR(100) NOT NULL
        DEFAULT 'gemini-embedding-001',

    embedding_dimensions SMALLINT NOT NULL
        DEFAULT 3072,

    -- pgvector halfvec supports indexed vectors up to
    -- 4000 dimensions in pgvector 0.8.7.
    embedding HALFVEC(3072),

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_hr_policy_chunk_number
        UNIQUE (policy_version_id, chunk_number),

    CONSTRAINT chk_hr_policy_chunk_number
        CHECK (chunk_number > 0),

    CONSTRAINT chk_hr_policy_chunk_text
        CHECK (BTRIM(chunk_text) <> ''),

    CONSTRAINT chk_hr_policy_page_number
        CHECK (page_number IS NULL OR page_number > 0),

    CONSTRAINT chk_hr_policy_embedding_model
        CHECK (embedding_model = 'gemini-embedding-001'),

    CONSTRAINT chk_hr_policy_embedding_dimensions
        CHECK (embedding_dimensions = 3072)
);

-- ------------------------------------------------------------
-- 4. RELATIONAL INDEXES
-- ------------------------------------------------------------

CREATE INDEX idx_hr_policies_status
    ON hr_policies(status);

CREATE INDEX idx_hr_policies_category
    ON hr_policies(policy_category);

CREATE INDEX idx_hr_policies_department
    ON hr_policies(department_id);

CREATE INDEX idx_hr_policy_versions_policy
    ON hr_policy_versions(policy_id, version_number DESC);

CREATE INDEX idx_hr_policy_versions_status
    ON hr_policy_versions(status);

CREATE INDEX idx_hr_policy_versions_effective_dates
    ON hr_policy_versions(effective_from, effective_to);

CREATE INDEX idx_hr_policy_chunks_version
    ON hr_policy_chunks(policy_version_id);

-- ------------------------------------------------------------
-- 5. VECTOR SIMILARITY INDEX
-- HNSW with cosine distance, using halfvec.
-- NULL embeddings are excluded from the index.
-- ------------------------------------------------------------

CREATE INDEX idx_hr_policy_chunks_embedding_hnsw
    ON hr_policy_chunks
    USING hnsw (embedding halfvec_cosine_ops)
    WITH (m = 16, ef_construction = 64)
    WHERE embedding IS NOT NULL;

-- ------------------------------------------------------------
-- 6. FULL-TEXT SEARCH
-- Complements vector search for exact words and policy terms.
-- ------------------------------------------------------------

ALTER TABLE hr_policy_chunks
    ADD COLUMN search_vector TSVECTOR
    GENERATED ALWAYS AS (
        TO_TSVECTOR(
            'english',
            COALESCE(section_heading, '') || ' ' || chunk_text
        )
    ) STORED;

CREATE INDEX idx_hr_policy_chunks_search_vector
    ON hr_policy_chunks
    USING GIN (search_vector);

COMMIT;
