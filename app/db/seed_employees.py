
from datetime import date

from sqlalchemy.exc import SQLAlchemyError

from app.db.session import SessionLocal
from app.models.department import Department
from app.models.employee import Employee


FIRST_NAMES = [
    "James", "John", "Robert", "Michael", "William",
    "David", "Richard", "Joseph", "Thomas", "Charles",
]

LAST_NAMES = [
    "Smith", "Johnson", "Brown", "Taylor", "Anderson",
]

JOB_TITLES = {
    "HR": "HR Executive",
    "FIN": "Accountant",
    "IT": "Software Engineer",
    "ADMIN": "Administrative Officer",
    "SALES": "Sales Executive",
    "MKT": "Marketing Executive",
    "OPS": "Operations Executive",
    "CS": "Customer Support Executive",
}


def seed_employees():
    db = SessionLocal()

    try:
        # Safety check: do not mix this initial seed with existing employees.
        existing_count = db.query(Employee).count()

        if existing_count > 0:
            raise ValueError(
                f"Employee table already contains {existing_count} records. "
                "Seeding cancelled to protect existing data."
            )

        departments = (
            db.query(Department)
            .filter(Department.is_active.is_(True))
            .order_by(Department.department_id)
            .all()
        )

        if len(departments) != 8:
            raise ValueError(
                f"Expected 8 active departments, found {len(departments)}."
            )

        for department in departments:
            if department.department_code not in JOB_TITLES:
                raise ValueError(
                    f"Unexpected department code: {department.department_code}"
                )

        employee_objects = []

        # Generate 50 deterministic synthetic employee records.
        for i in range(50):
            department = departments[i % len(departments)]

            first_name = FIRST_NAMES[i % len(FIRST_NAMES)]
            last_name = LAST_NAMES[i // len(FIRST_NAMES)]

            full_name = f"{first_name} {last_name}"
            email = f"employee{i + 1:03d}@example.com"

            # First employee assigned to each department is its manager.
            is_department_manager = i < len(departments)

            employee = Employee(
                full_name=full_name,
                email=email,
                department=department.department_name,
                department_id=department.department_id,
                job_title=(
                    "Department Manager"
                    if is_department_manager
                    else JOB_TITLES[department.department_code]
                ),
                hire_date=date(
                    2021 + (i % 6),
                    (i % 12) + 1,
                    (i % 27) + 1,
                ),
                is_active=True,
            )

            db.add(employee)
            employee_objects.append((employee, department.department_id))

        # Insert employees and retrieve their generated IDs.
        db.flush()

        # Assign each department's other employees to its manager.
        department_managers = {}

        for employee, department_id in employee_objects:
            if department_id not in department_managers:
                department_managers[department_id] = employee.employee_id

        for employee, department_id in employee_objects:
            manager_id = department_managers[department_id]

            if employee.employee_id != manager_id:
                employee.manager_employee_id = manager_id

        db.commit()

        print("=" * 55)
        print("EMPLOYEE SEEDING COMPLETED")
        print("=" * 55)
        print(f"New employees inserted: {len(employee_objects)}")
        print(f"Departments covered: {len(departments)}")
        print(f"Department managers: {len(department_managers)}")
        print("Employee codes: Generated by PostgreSQL")
        print("Email domain: example.com (synthetic data)")

    except (SQLAlchemyError, ValueError) as error:
        db.rollback()
        print("Employee seeding failed.")
        print(f"Reason: {error}")
        raise

    finally:
        db.close()


if __name__ == "__main__":
    seed_employees()
